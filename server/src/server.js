import dotenv from 'dotenv';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import express from 'express';
import cors from 'cors';
import helmet from 'helmet';
import rateLimit from 'express-rate-limit';
import { connectDatabase } from './config/db.js';
import trainRoutes from './routes/trainRoutes.js';
import searchRoutes from './routes/searchRoutes.js';
import { getProviderStatus } from './services/railDataService.js';

const serverDir = path.dirname(fileURLToPath(import.meta.url));
dotenv.config({ path: process.env.ENV_FILE || path.resolve(serverDir, '../../.env') });
const app = express();
const port = Number(process.env.PORT || 5000);
app.disable('x-powered-by');
app.use(helmet({ crossOriginResourcePolicy: { policy: 'cross-origin' } }));
app.use(cors({ origin: (process.env.CLIENT_URL || 'http://localhost:5173').split(',').map((item) => item.trim()) }));
app.use(express.json({ limit: '20kb' }));
app.use('/api', rateLimit({ windowMs: 60_000, limit: 100, standardHeaders: 'draft-8', legacyHeaders: false }));
app.get('/api/health', (_req, res) => res.json({ success: true, service: 'RailPulse API', timestamp: new Date().toISOString(), provider: getProviderStatus() }));
app.use('/api/trains', trainRoutes);
app.use('/api/search', searchRoutes);
app.use((_req, res) => res.status(404).json({ success: false, message: 'API route not found.' }));
app.use((error, _req, res, _next) => {
  console.error('[api error]', error.message);
  res.status(Number(error.statusCode) || 500).json({ success: false, message: Number(error.statusCode) === 500 ? 'The server could not complete the request. Check server logs and provider settings.' : error.message });
});
await connectDatabase();
app.listen(port, () => console.log(`[server] RailPulse API listening on http://localhost:${port} — mode: ${getProviderStatus().mode}`));
